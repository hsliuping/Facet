#!/usr/bin/env python3
"""账本 → 种子渠道：由 ledger/vendors/*.json 生成 src/facet/gateway/seed_channels.json。

    python tools/ledger/gen_seed.py            # 重新生成（先校验账本）
    python tools/ledger/gen_seed.py --selftest # 临时账本上验证生成规则

seed.py 首启时读这份 JSON 合成 seed config；anthropic / openai 两个协议占位渠道
不是账本事实，仍留在 seed.py 里手写。规则：
  * 纯付费厂家（无免费模型、无 per_model、无活动包）不进种子；
  * 每个进种子的厂家一个渠道，名字 = 厂家 id，enabled=False（用户填 key 后手动启用）；
  * protocol/base_url 取 endpoints（优先 openai，其次 anthropic，皆无则跳过）；
  * models.auto 取首个 tier=free 模型，没有则取首个模型；
  * per_model 额度 + 已核实活动包额度 → model_quota（一次性开库余额）；
  * tier：有免费模型 → free，否则 paid；
  * api_key = env:<厂家>_API_KEY；
  * 路由：default = 头两个免费渠道 + $free；cheap = 全部 + $free；
    free = 有免费模型的渠道 + $free（纯一次性包不进「永不耗尽」链）。

改账本后必须重跑本脚本（CI 可加一步），seed_channels.json 头部有 GENERATED 标记。
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

DEFAULT_LEDGER = Path(__file__).resolve().parents[2] / "ledger"
OUT_PATH = Path(__file__).resolve().parents[2] / "src" / "facet" / "gateway" / "seed_channels.json"

HEADER = (
    "// GENERATED by tools/ledger/gen_seed.py from ledger/vendors/*.json — DO NOT EDIT.\n"
    "// Regenerate after ledger changes: python tools/ledger/gen_seed.py\n"
)


def load_ledger(ledger: Path) -> tuple[list[dict], list[dict]]:
    """按 id 排序返回 (vendors, activities)；status != active 的厂家跳过。"""
    vendors, activities = [], []
    for dirname, sink in (("vendors", vendors), ("activities", activities)):
        directory = ledger / dirname
        if not directory.is_dir():
            continue
        for path in sorted(directory.glob("*.json")):
            sink.append(json.loads(path.read_text(encoding="utf-8")))
    vendors = [v for v in vendors if v.get("status", "active") == "active"]
    return vendors, activities


def pick_protocol(endpoints: dict) -> tuple[str, str] | None:
    """返回 (protocol, base_url)：优先 openai，其次 anthropic；两者皆无则跳过。"""
    for key in ("openai", "anthropic"):
        if key in endpoints:
            return key, endpoints[key]
    return None


def channel_for(vendor: dict, activity_grants: dict[str, int]) -> dict | None:
    models = vendor.get("models") or []
    if not models:
        return None  # 无模型登记的厂家不进种子
    frees = [m["id"] for m in models if m.get("tier") == "free"]
    per_model = (vendor.get("free_quota") or {}).get("per_model") or {}
    if not frees and not per_model and not activity_grants:
        return None  # 纯付费厂家：用户真要时手填，不占种子
    picked = pick_protocol(vendor.get("endpoints") or {})
    if picked is None:
        return None  # 网关不支持该协议（如 gemini 原生端点）
    protocol, base_url = picked
    channel = {
        "name": vendor["id"],
        "protocol": protocol,
        "provider": vendor["id"],
        "mode": "payg",
        "base_url": base_url,
        "api_key": f"env:{vendor['id'].upper()}_API_KEY",
        "enabled": False,
        "tier": "free" if frees else "paid",
        "models": {"auto": frees[0] if frees else models[0]["id"]},
    }
    if per_model or activity_grants:
        model_quota = {}
        for model, quota in per_model.items():
            model_quota[model] = {
                "tokens": quota["tokens"] + activity_grants.get(model, 0),
                "period": "total",
            }
        for model, tokens in activity_grants.items():
            if model not in model_quota:
                model_quota[model] = {"tokens": tokens, "period": "total"}
        channel["model_quota"] = model_quota
    return channel


def activity_grants_for(vendor_id: str, activities: list[dict]) -> dict[str, int]:
    """该厂家已核实的活动包额度：model -> tokens 合计（一次性开库余额）。"""
    grants: dict[str, int] = {}
    for act in activities:
        if act.get("vendor") != vendor_id:
            continue
        if act.get("status") not in ("verified", "published"):
            continue
        grant = act.get("grant") or {}
        model, tokens = grant.get("model"), grant.get("tokens")
        if model and tokens:
            grants[model] = grants.get(model, 0) + tokens
    return grants


def build_seed_data(vendors: list[dict], activities: list[dict]) -> dict:
    channels = [c for c in (channel_for(v, activity_grants_for(v["id"], activities))
                            for v in vendors) if c]
    by_name = {c["name"]: c for c in channels}
    long_term = [c["name"] for c in channels if c["tier"] == "free"]
    packs = [c["name"] for c in channels
             if c["tier"] != "free" and "model_quota" in c]
    routes = {
        "default": long_term[:2] + ["$free"],
        "cheap": [n for n in by_name if n in long_term or n in packs] + ["$free"],
        "free": long_term + ["$free"],
    }
    return {"channels": channels, "routes": routes}


def generate(ledger: Path, out: Path) -> dict:
    vendors, activities = load_ledger(ledger)
    data = build_seed_data(vendors, activities)
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    out.write_text(HEADER + payload, encoding="utf-8")
    return data


