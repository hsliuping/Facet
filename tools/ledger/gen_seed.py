def _selftest() -> bool:
    import tempfile

    ok = True

    with tempfile.TemporaryDirectory() as tmp:
        ledger = Path(tmp)
        (ledger / "vendors").mkdir()
        docs = [GOOD_VENDOR, PACK_VENDOR, PAID_VENDOR, DEPRECATED_VENDOR]
        for doc in docs:
            (ledger / "vendors" / f"{doc['id']}.json").write_text(
                json.dumps(doc, ensure_ascii=False), encoding="utf-8")
        out = Path(tmp) / "seed_channels.json"
        data = generate(ledger, out)

        # 1. 渠道由账本生成：名字/端点/模型/额度/env 名
        names = [c["name"] for c in data["channels"]]
        expect = names == ["acme", "packco"]
        print(("ok   " if expect else "FAIL ") + f"渠道名单 {names}")
        ok &= expect

        acme = data["channels"][0]
        expect = (acme["base_url"] == "https://api.acme.example/v1"
                  and acme["models"]["auto"] == "acme-lite"
                  and acme["api_key"] == "env:ACME_API_KEY"
                  and acme["tier"] == "free"
                  and "model_quota" not in acme)  # acme 的 per_model 只在
        print(("ok   " if expect else "FAIL ") + "acme 渠道字段")
        ok &= expect

        packco = data["channels"][1]
        expect = (packco["protocol"] == "anthropic"
                  and packco["model_quota"]["pack-model"]["tokens"] == 5000000)
        print(("ok   " if expect else "FAIL ") + "packco 额度进 model_quota")
        ok &= expect

        # 2. 路由：包渠道进 cheap 不进 free；default 取头两个长期免费
        free_route = data["routes"]["free"]
        expect = ("packco" not in free_route and "acme" in free_route
                  and "$free" in free_route)
        print(("ok   " if expect else "FAIL ")
              + f"free 路由排除包渠道 {free_route}")
        ok &= expect
        expect = data["routes"]["cheap"] == ["acme", "packco", "$free"]
        print(("ok   " if expect else "FAIL ")
              + f"cheap 路由 {data['routes']['cheap']}")
        ok &= expect
        expect = data["routes"]["default"] == ["acme", "$free"]
        print(("ok   " if expect else "FAIL ")
              + f"default 路由 {data['routes']['default']}")
        ok &= expect

        # 3. 落盘带 GENERATED 头；deprecated 厂家与不支持协议被跳过
        expect = out.is_file() and "GENERATED" in out.read_text(
            encoding="utf-8").splitlines()[0]
        print(("ok   " if expect else "FAIL ") + "落盘 GENERATED 头")
        ok &= expect
        vendors, activities = load_ledger(ledger)
        expect = [v["id"] for v in vendors] == ["acme", "packco", "paidco"]
        print(("ok   " if expect else "FAIL ")
              + f"deprecated 厂家被跳过 {[v['id'] for v in vendors]}")
        ok &= expect

        # 4. 活动包并入开库余额；gemini 端点与纯付费厂家不进种子
        (ledger / "vendors" / "packco2.json").write_text(
            json.dumps(dict(PACK_VENDOR, id="packco2"), ensure_ascii=False),
            encoding="utf-8")
        (ledger / "vendors" / "gproto.json").write_text(
            json.dumps(dict(GOOD_VENDOR, id="gproto",
                            endpoints={"gemini": "https://x.example"}),
                       ensure_ascii=False), encoding="utf-8")
        act_dir = ledger / "activities"
        act_dir.mkdir()
        (act_dir / "act.json").write_text(json.dumps({
            "id": "act-1", "vendor": "packco2", "status": "verified",
            "grant": {"type": "activity_package", "model": "pack-model",
                      "tokens": 2000000},
        }, ensure_ascii=False), encoding="utf-8")
        data = build_seed_data(*load_ledger(ledger))
        expect = [c["name"] for c in data["channels"]] == ["acme", "packco",
                                                           "packco2"]
        pack = data["channels"][2]
        expect &= pack["model_quota"]["pack-model"]["tokens"] == 7000000
        print(("ok   " if expect else "FAIL ")
              + f"活动包并入开库余额且跳过不支持协议 {pack['model_quota']}")
        ok &= expect

    return ok


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--ledger", type=Path, default=DEFAULT_LEDGER,
                        help="账本目录（默认仓库根 ledger/）")
    parser.add_argument("--out", type=Path, default=OUT_PATH,
                        help="输出 JSON（默认 src/facet/gateway/seed_channels.json）")
    parser.add_argument("--selftest", action="store_true",
                        help="临时账本上自测生成规则，不碰真实账本")
    args = parser.parse_args()

    if args.selftest:
        print("自测开始（临时账本）…")
        passed = _selftest()
        print("自测通过" if passed else "自测失败")
        return 0 if passed else 1

    data = generate(args.ledger.resolve(), args.out)
    n_free = sum(1 for c in data["channels"] if c["tier"] == "free")
    print(f"已生成 {args.out}：{len(data['channels'])} 个渠道"
          f"（{n_free} 个免费），default={data['routes']['default']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
