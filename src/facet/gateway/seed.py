"""First start: generate a seed config with a set of disabled free-tier
templates the user can enable after registering keys.

Reads seed_channels.json (GENERATED by tools/ledger/gen_seed.py from
ledger/vendors/*.json) so vendor facts live in exactly one place — adding a
vendor to the ledger and re-running the generator updates the seed; this file
is never hand-edited for vendor data. anthropic / openai protocol
placeholders are not ledger facts and stay hardcoded below.

If seed_channels.json is missing (broken install), the seed degrades to the
two protocol placeholders only — still a valid config, just fewer templates.
"""
from __future__ import annotations

import json
from pathlib import Path

SEED_CHANNELS_PATH = Path(__file__).with_name("seed_channels.json")

# Protocol placeholders: not vendor facts, so not generated from the ledger.
# openai-embeddings keeps the embedding route alive out of the box;
# anthropic-template keeps the Anthropic-protocol route alive out of the box.
PLACEHOLDER_CHANNELS = [
    {
        "name": "openai-embeddings",
        "protocol": "openai",
        "provider": "openai",
        "mode": "payg",
        "base_url": "https://api.openai.com/v1",
        "api_key": "env:OPENAI_API_KEY",
        "enabled": False,
        "tier": "paid",
        "models": {"auto": "text-embedding-3-small"},
    },
    {
        "name": "anthropic-template",
        "protocol": "anthropic",
        "provider": "anthropic",
        "mode": "payg",
        "base_url": "https://api.anthropic.com",
        "api_key": "env:ANTHROPIC_API_KEY",
        "enabled": False,
        "tier": "paid",
        "models": {"auto": "claude-haiku-4-5"},
    },
]


def load_seed_channels() -> dict:
    """读账本生成的种子渠道数据；文件缺失时返回空（仅协议占位渠道）。"""
    try:
        text = SEED_CHANNELS_PATH.read_text(encoding="utf-8")
    except OSError:
        return {"channels": [], "routes": {}}
    # 头部 GENERATED 注释行以 // 开头，JSON 本身从第二行起
    lines = text.splitlines()
    payload = json.loads("\n".join(l for l in lines if not l.startswith("//")))
    return {"channels": payload.get("channels", []),
            "routes": payload.get("routes", {})}


def build_seed() -> dict:
    generated = load_seed_channels()
    channels = generated["channels"] + PLACEHOLDER_CHANNELS
    routes = [
        {"name": "default", "protocol": "openai",
         "channels": generated["routes"].get("default", ["$free"])},
        {"name": "default", "protocol": "anthropic",
         "channels": ["anthropic-template"]},
        {"name": "cheap", "protocol": "openai",
         "channels": generated["routes"].get("cheap", ["$free"])},
        {"name": "free", "protocol": "openai",
         "channels": generated["routes"].get("free", ["$free"])},
        {"name": "embedding", "protocol": "openai",
         "channels": ["openai-embeddings"]},
    ]
    return {
        "listen": {"host": "127.0.0.1", "port": 8787},
        # listen.admin_key intentionally unset: the console asks for a fresh
        # password on first open (/setup) instead of shipping a known default.
        "channels": channels,
        "routes": routes,
        "defaults": {"maintenance_model": "auto"},
        "models": {
            # The console's 模型接入 page reads raw config `models.branded`:
            # brand the built-in models to the seed's first-start routes so a
            # fresh install lands on real chains instead of the fallback.
            "branded": {
                "facet-auto": "default",
                "facet-cheap": "cheap",
                "facet-free": "free",
                "facet-agent": "default",
                "facet-embedding": "embedding",
            },
        },
        "setup": {
            "token": "facet-setup-please-change",
            "enabled": True,
        },
    }


def write_seed(path: Path) -> None:
    """Write the seed config if path does not exist (idempotent first start).

    The seed templates are all enabled=false, so the $free macro expands to
    nothing and is harmless (the chains also carry explicit channels, so the
    "macro missed" error is not triggered). Route channels may name
    not-yet-enabled templates: they simply fail over to nothing until the
    user enables one.
    """
    if path.exists():
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build_seed(), ensure_ascii=False, indent=2) + "\n",
                    encoding="utf-8")


def print_seed_banner(config_path: Path) -> None:
    generated = load_seed_channels()
    templates = [c for c in generated["channels"] + PLACEHOLDER_CHANNELS
                 if c.get("enabled") is False]
    env_vars = sorted({c["api_key"].split(":", 1)[1] for c in templates})
    print("=" * 60)
    print("首启引导：seed config 已生成")
    print(f"  {config_path}")
    print("=" * 60)
    print("  管理密码未设置：首次打开管理控制台时设置（建议立即更换）")
    print(f"  管理控制台: http://127.0.0.1:8787/admin")
    print(f"  预置渠道（{len(templates)} 个，均未启用）:")
    for name in sorted(c["name"] for c in templates):
        print(f"    - {name}")
    print(f"  注册后填入 key 并启用：{', '.join(env_vars)}")
    print("=" * 60)
